CREATE TABLE IF NOT EXISTS decks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS flags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deck_id BIGINT NOT NULL,
    front TEXT NOT NULL DEFAULT '',
    back TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_notes_deck
        FOREIGN KEY (deck_id)
        REFERENCES decks(id)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS note_flags (
    note_id BIGINT NOT NULL,
    flag_id BIGINT NOT NULL,

    PRIMARY KEY (note_id, flag_id),

    CONSTRAINT fk_note_flags_note
        FOREIGN KEY (note_id)
        REFERENCES notes(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_note_flags_flag
        FOREIGN KEY (flag_id)
        REFERENCES flags(id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_notes_deck_id
    ON notes(deck_id);

CREATE INDEX IF NOT EXISTS idx_note_flags_flag_id
    ON note_flags(flag_id);
